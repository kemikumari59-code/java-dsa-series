public class Variable {
    static void main() {
        //create // declare
        int age;
        //System.out.println(age);
        //assign value
        age = 11;
        System.out.println(age);
        //define or initialize
        int totalMarks = 20;
        System.out.println(totalMarks);
        //Case Sensitive
        int weight = 78;
        int WEIGHT = 56;
        System.out.println("weight:" + weight);
        System.out.println("weight:" + WEIGHT);
        //Subsequent Letters
        int height5 = 21;
        //No Reserved keywords
        // int class = 45;
        //length
        int hello = 100;
        int a = 1;
        int b = 2;



    }
}
